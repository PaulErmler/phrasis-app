import type {
  GraderMetadata,
  LlmVerdict,
  NoteType,
} from '../../convex/lib/writingFeedbackPrompt';

/**
 * Fixtures for scripts/eval-writing-feedback.ts.
 *
 * The prompt itself is language-neutral on purpose, so the cases carry the
 * language coverage: if an abstract rule only works for the pair it was
 * written against, that shows up here as a verdict or note-type miss on some
 * other pair. Scripts span Latin, Cyrillic, Greek, CJK, Devanagari, and RTL
 * Arabic, and every case carries a CEFR level so the report can show whether
 * accuracy holds as the sentences get harder.
 *
 * `expectVerdict` is the grade a competent teacher would give. Where a case is
 * genuinely arguable, `alsoAcceptable` widens it rather than pretending the
 * boundary is sharp — a case that fails for everyone teaches nothing.
 */
/**
 * The error class the case exercises. The report breaks accuracy down by this,
 * so a prompt change that fixes spelling notes while breaking negation shows
 * up as a class regression rather than a two-point drop in the total.
 */
export type ErrorKind =
  | 'synonym'
  | 'antonym'
  | 'negation'
  | 'spelling'
  | 'punctuation'
  | 'formality'
  | 'gender'
  | 'number'
  | 'missingWords'
  | 'extraWords'
  | 'wordOrder'
  | 'grammarForm'
  | 'preposition'
  | 'falseFriend'
  | 'sentenceType'
  | 'wrongLanguage'
  | 'degenerate'
  | 'injection'
  | 'notesLanguage'
  // Phenomena that only exist in some language families, which is exactly why
  // a language-neutral prompt has to be checked against them.
  | 'aspect'
  | 'classifier'
  | 'nounClass'
  | 'definiteness'
  | 'separableVerb'
  | 'toneDiacritic'
  | 'evidentiality'
  | 'honorific'
  | 'numeralAgreement'
  | 'compound'
  // Ways a learner can be wrong that are not about grammar at all.
  | 'regionalVariant'
  | 'scriptVariant'
  | 'collocation'
  | 'diacriticsStripped'
  | 'duplicatedWord'
  | 'offTopic';

export type EvalCase = {
  id: string;
  kind: ErrorKind;
  /** Language of the source sentence, which the learner translates FROM. */
  baseLanguage: string;
  /** Language the answer is written and graded in. */
  targetLanguage: string;
  /** Language the note prose must be written in. */
  notesLanguage: string;
  /**
   * Roughly how hard the sentence is. The grader is not told the level — the
   * point is to check that one prompt handles "I would like a coffee" and a
   * counterfactual conditional equally well.
   */
  cefr: 'A1' | 'A2' | 'B1' | 'B2' | 'C1';
  baseText: string;
  expected: string;
  metadata?: GraderMetadata;
  answer: string;
  expectVerdict: LlmVerdict;
  alsoAcceptable?: LlmVerdict[];
  expectNoteType?: NoteType | NoteType[];
  expectAltOk?: boolean;
  /** At least one of these must appear in the note prose (case-insensitive). */
  mustMention?: string[];
  /** None of these may appear — usually the BASE word the learner already read. */
  mustNotMention?: string[];
  /** Why this case is in the set. Printed next to a failure. */
  why: string;
};

